# ---- download -----------------------------------------------------------------------------------------------------------------
fetch() { # url dest
  if command -v curl >/dev/null 2>&1; then curl -fsSL --proto '=https,file' --tlsv1.2 --retry 3 -o "$2" "$1" 2>/dev/null || curl -fsSL --retry 3 -o "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then wget -q -O "$2" "$1"
  else die "$(t sh_e_curl)"; fi
}
