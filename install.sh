        fi
        out+="$idx$ch"
      done
      printf '%s%s\n' "$out" "$R"
    else printf '  %s\n' "$row"; fi
  done
  printf '  %s%s%s  %s·%s  %sinstaller v%s%s\n\n' "$B" "$(t tagline)" "$R" "$D" "$R" "$D" "$INSTALLER_VERSION" "$R"
}

