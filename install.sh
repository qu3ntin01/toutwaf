detect_lang() {
  if [ -z "$LANG_CODE" ]; then
    local l="${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}"; LANG_CODE="${l%%[_.@-]*}"
  fi
  LANG_CODE="$(printf '%s' "$LANG_CODE" | tr 'A-Z' 'a-z')"
  case "$LANG_CODE" in en|fr|es|de|it|pt|nl|ru|zh|ar) ;; *) LANG_CODE=en ;; esac
  case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in *[Uu][Tt][Ff]-8*|*[Uu][Tt][Ff]8*) ;; *) LANG_CODE=en ;; esac
}
