  case "$a" in
    --en|--fr|--es|--de|--it|--pt|--nl|--ru|--zh|--ar) LANG_CODE="${a#--}" ;;
    --lang=*) LANG_CODE="${a#--lang=}" ;;
    *) [ "$prev" != --lang ] || LANG_CODE="$a" ;;
  esac
  prev="$a"
