  fetch "$REL/$ASSET" "$TMP/$ASSET" || die "$(t sh_e_dl "$REL/$ASSET")"
  GOT_SUM="$(sha256sum "$TMP/$ASSET" | cut -d' ' -f1)"
  [ "$GOT_SUM" = "$WANT_SUM" ] || die "$(t e_sha "$ASSET" "$WANT_SUM" "$GOT_SUM")"
  say "$(t s_sha_ok)"
  mkdir -p "$TMP/x"
  tar -xzf "$TMP/$ASSET" -C "$TMP/x" --no-same-owner
  SRC="$TMP/x/toutwaf-backup-linux-$ARCH"
  [ -x "$SRC/toutwaf-backup" ] || die "$(t sh_e_noexe)"
  GOT_VER="$("$SRC/toutwaf-backup" version 2>/dev/null | sed -nE 's/^toutwaf-backup ([^ ]+).*/\1/p' || true)"
  [ "$GOT_VER" = "$WANT" ] || warn "$(t sh_w_binver "${GOT_VER:-?}" "$WANT")"
  mkdir -p "$BIN_DIR"
  if [ -f "$BIN" ]; then cp -p "$BIN" "$BIN.prev"; fi
  install -m 0755 "$SRC/toutwaf-backup" "$BIN.new.$$"
  mv -f "$BIN.new.$$" "$BIN"
  say "$(t s_installed "$BIN" "$WANT")"
  if [ -f "$BIN.prev" ] && [ -n "$CUR" ]; then say "$(t sh_s_prev "$CUR" "$BIN.prev")"; fi
  UNIT_SRC="$SRC/systemd"
fi

