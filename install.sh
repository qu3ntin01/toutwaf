VERSION="${TOUTWAF_VERSION:-latest}"
COMPONENT="${TOUTWAF_COMPONENT:-all}"          # dp | cp | all
# Layout: one installation HOME (default /var/toutwaf) holding bin/ conf/ data/ logs/. An existing installation keeps its own paths
