  local stamp="${TWB_STAMP:-/var/lib/toutwaf-backup-system-update.stamp}" pm rc=0 log="$TMP/sysupdate.log" to=()
  if [ "${TWB_FORCE_SYSUPDATE:-}" != 1 ] && [ -n "$(find "$stamp" -mmin -360 2>/dev/null || true)" ]; then say "  $(t su_recent)"; return 0; fi
