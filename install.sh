  fetch "$REL/$ASSET" "$TMP/$ASSET" || die "$(t sh_e_dl "$REL/$ASSET")"
  GOT_SUM="$(sha256sum "$TMP/$ASSET" | cut -d' ' -f1)"
  [ "$GOT_SUM" = "$WANT_SUM" ] || die "$(t e_sha "$ASSET" "$WANT_SUM" "$GOT_SUM")"
