        Set-Content -Path $f -Value '' -Encoding UTF8
        icacls $f /inheritance:r /grant:r '*S-1-5-32-544:F' '*S-1-5-18:F' | Out-Null
        $lines = @(('ToutWAF {0} - {1}Z' -f (T 'sum_title'), (Get-Date).ToUniversalTime().ToString('s')))
